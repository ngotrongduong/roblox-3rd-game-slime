"""Turns the upload_image answer (art/faces/upload_result.json) into art/faces/ids.json (sprite name -> asset id)
and writes src/shared/FaceArt.luau from faces.json + ids.json.

  python tools/faces/make_ids.py            (merges: ids that failed to upload keep their old id)
"""

import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FACES = os.path.join(ROOT, "art", "faces")
faces = json.load(open(os.path.join(FACES, "faces.json")))
ids_path = os.path.join(FACES, "ids.json")
ids = json.load(open(ids_path)) if os.path.exists(ids_path) else {}
raw = open(os.path.join(FACES, "upload_result.json"), encoding="utf-8").read()
start = raw.index("{")
res = json.loads(raw[start:])
by_file = {s["file"]: n for n, s in faces["sprites"].items()}
missing = []
for url, val in res.items():
    f = url.split("localhost:8794/")[1]
    m = re.match(r"rbxassetid://(\d+)$", val)
    if m:
        ids[by_file[f]] = int(m.group(1))
    else:
        missing.append(f)
json.dump(ids, open(ids_path, "w"), indent=1, sort_keys=True)
print("ids", len(ids), "of", len(faces["sprites"]), "failed:", missing)

lines = [
    "--!strict",
    "-- GENERATED by tools/faces/make_ids.py from art/faces/faces.json and ids.json: do not edit by hand.",
    "-- Every face part the slime face is built from: the owner's own pixels cut from slime.emotion.<id>.png",
    '-- (source "owner") and the few pieces drawn in the same style (source "drawn", to be replaced by art).',
    "-- w, h, cx, cy are in body heights (cx, cy: the sprite centre from the face centre, x right, y up);",
    "-- `px` is the picture's size in pixels. The face centre sits at `FaceHeight` of the body height.",
    "local FaceArt = {}",
    "",
    "FaceArt.FaceHeight = %s" % faces["faceHeightUnit"],
    "FaceArt.Navy = { r = %d, g = %d, b = %d } -- the owner's line colour, measured from his mouth pictures" % tuple(faces["navy"]),
    "",
    "export type Sprite = { id: number, source: string, w: number, h: number, cx: number, cy: number, px: number }",
    "",
    "FaceArt.Sprites = {",
]
for n in sorted(faces["sprites"]):
    s = faces["sprites"][n]
    lines.append(
        '\t%s = { id = %d, source = "%s", w = %.5f, h = %.5f, cx = %.5f, cy = %.5f, px = %d },'
        % (n, ids.get(n, 0), s["source"], s["w"], s["h"], s["cx"], s["cy"], s["px"][0])
    )
lines += ["} :: { [string]: Sprite }", "", "return FaceArt", ""]
open(os.path.join(ROOT, "src", "shared", "FaceArt.luau"), "w", newline="\n").write("\n".join(lines))
